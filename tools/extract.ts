/**
 * Pull the look out of Quire Ink and into the theme, by RUNNING Quire Ink's own emitters.
 *
 * Nothing here retypes a colour, a size or a rule. `tools/tsconfig.json` maps `@/*` at the
 * sibling checkout, so every value below is the value the live site renders with; when the
 * blog's front end moves, this is re-run rather than re-read. The Quire Ink commit it was
 * taken from is written into the manifest, so a stale copy is a diff and not a guess.
 *
 * Emits, into theme/:
 *   assets/css/quireink-base.css   the hand-written public sheet (PUBLIC_CSS), less the IDE chrome
 *   assets/css/quireink-ide.css    the IDE chrome, so it can be left unloaded when it is off
 *   rtl.css                        the mirrored diff of all four sheets, for an RTL locale
 *   assets/css/editor.css          the article's own rules, addressed at the editor canvas
 *   assets/css/quireink-tokens.css palette + type scale + shape, for DEFAULT_SETTINGS
 *   assets/fonts/*.woff2           the self-hosted faces the default preset can reach
 *   theme.json                     the same palette and scale, in the block editor's dialect
 *   ../tools/extract-manifest.json what came from where, and at which commit
 */
import { mkdir, writeFile, readdir, copyFile, rm } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { $ } from 'bun'

import { PUBLIC_CSS } from '@/web/public.css'
import { IDE_CSS } from '@/web/ide.css'

import { flipCss } from './rtl'
import { DEFAULT_SETTINGS } from '@/content/settings'
import {
  themesToCss, fontPresetCss, chromeFontCss, THEME_PRESETS, TYPE_ROLES,
} from '@/content/themes'
import { cjkLangCss } from '@/content/fonts'
import { typographyToCss, shapeToCss, tableToCss } from '@/content/settings'
import { allFontFaceCss, MONO_TRACKING } from '@/render/font-faces'
import { singleRailCss, timelineCss, RAIL_W, RAIL_GAP } from '@/render/rail-css'

import { APPEARANCE_PHP, APPEARANCE_COUNTS } from './appearance-php'
import { editorCss } from './editor-css'
import { FONT_PRESETS, CHROME_FONTS, SCHEMES } from '@/content/themes'

const HERE = dirname(import.meta.dir)
const QUIRE = join(HERE, '..', 'quireink')
// Normally the theme itself. `EXTRACT_OUT` points it elsewhere so
// `tools/checks/generated-in-sync.ts` can produce a fresh copy and compare bytes without
// touching what is committed — a check that has to modify the tree to run is a check people
// turn off.
const THEME = process.env.EXTRACT_OUT ?? join(HERE, 'quire-ink')

const s = DEFAULT_SETTINGS

// ---------------------------------------------------------------- the two sheets

// The order is `layout.ts`'s `pageStyles()`, which is load-bearing: --density must be
// declared before the block that multiplies it into --sp, and the palette before the type
// scale. Read the two side by side when either moves.
//
// Four entries of that list are left out, and all four for the same reason: on DEFAULT
// settings they emit the empty string. `selectionCss` and `penGesturesCss` only speak when
// an owner has changed an ink or switched a gesture off; `figureCss` says nothing when the
// site-wide frame is 'none', which is the default; `galleryCss` the same. A theme has no
// owner yet, so there is nothing for them to say — and each becomes a Customizer control
// here on the day it does.
const tokens = [
  '/* Generated by tools/extract.ts — do not edit. Run `bun tools/extract.ts`. */',
  allFontFaceCss(),
  // The three font HANDLES. Missing this block was invisible in a diff and obvious on a
  // screen: `--font-reading` is what `.prose` asks for, and with no declaration the article
  // fell back to the browser's serif while every other part of the page looked correct.
  `:root{--font-sans:'Inter', 'Inter Fallback', system-ui, -apple-system, 'Segoe UI', sans-serif;`
    + `--font-reading:var(--font-sans);`
    + `--font-mono:'JetBrains Mono', ui-monospace, 'SFMono-Regular', Menlo, Consolas, monospace}`,
  // The reading column. `.wrap` reads `--shell-w` with a 42rem fallback, so a missing
  // declaration is not a broken page — it is a page that quietly ignores the setting.
  `:root{--shell-w:${s.contentWidth}px}`,
  // The desktop rail, and the reason the table of contents did not appear at 1440px on the
  // first screenshot: below the breakpoint `.rail` is a slide-out drawer, and ONLY these
  // generated rules promote it into the gutter. They are generated rather than written
  // because a media query cannot read a CSS variable and the breakpoint is COMPUTED from
  // the column width — the rail moves out only when there is room on BOTH sides, so the
  // column stays centred.
  singleRailCss(s.contentWidth),
  // The listing's gutter timeline: the spine, the sticky year tag and the month markers.
  // In the blog engine this arrives through `pageStyles(settings, extra)` because it is
  // page-specific; a theme has one stylesheet for every page, so it is emitted here and is
  // inert on a page with no `.tl-*` in it.
  //
  // It has to be emitted at all, and that is not obvious: the base sheet styles what a year
  // tag LOOKS like, and only this function positions it. Without it the markers do not sit
  // in the gutter — they sit in the text, in reading order, and the feed reads as if
  // somebody typed the month into the middle of the page. Its first line is
  // `.tl-mark,.tl-year{display:none}`, so the fallback is invisible rather than wrong.
  //
  // Its breakpoint is LOWER than the rail's, deliberately: a month label needs ~130px of
  // gutter and a sidebar needs 250px, so the timeline shows on a laptop where the sidebar
  // has already folded away.
  timelineCss(s.contentWidth),
  fontPresetCss(s.fontPreset),
  cjkLangCss(s.fontPreset),
  chromeFontCss(s.chromeFont),
  themesToCss(s.themes, s.themePreset, undefined, s.defaultScheme),
  shapeToCss(s.shape),
  tableToCss(s.table),
  typographyToCss(s.typography),
  MONO_TRACKING,
].filter(Boolean).join('\n')
  // Quire Ink serves its faces from the site root; a WordPress theme is a folder somewhere
  // under wp-content. Relative is the answer that needs no PHP: a url() in a stylesheet
  // resolves against THAT stylesheet, and both directories are siblings under assets/.
  .replaceAll("url('/fonts/", "url('../fonts/")

// The IDE chrome comes out into its own sheet, because it is the one part of the base sheet
// an owner can switch off - and switching it off should stop it being downloaded, not just
// stop it applying. Measured on the sheet as it stands: 17,705 B raw, 5,652 B of gzip that a
// reader with the switch off no longer pays. Whoever leaves it on pays 839 B of gzip for the
// second file, because the same bytes compress slightly worse split in two, and one more
// request on a connection that is already open. The block editor never loads it at all: not
// one rule in it touches `.prose`, so in the editor it was 6.5 KB that could not match.
//
// It is LIFTED, never re-typed. `IDE_CSS` is a contiguous slice of `PUBLIC_CSS` and this
// removes exactly that slice; if the blog engine ever composes the sheet differently the
// slice stops matching and this throws, which is the seam reporting rather than a theme
// quietly shipping the chrome twice.
//
// Order does not matter for where it is loaded, and that is a property rather than a hope:
// every selector in it carries `html[data-ide-chrome=on]`, so it cannot tie with anything
// else in the theme and cannot lose a tie it never has. Checked, along with the fact that it
// shares no selector at all with the mobile or print sheets it used to sit in front of.
const IDE_SLICE = '\n' + IDE_CSS + '\n'
if (!PUBLIC_CSS.includes(IDE_SLICE)) {
  throw new Error(
    'IDE_CSS is no longer a contiguous slice of PUBLIC_CSS.\n'
    + '  Quire Ink has changed how src/web/public.css.ts composes the sheet.\n'
    + '  Read that file, then decide whether the IDE chrome can still be lifted out;\n'
    + '  do NOT paste the rules in here.',
  )
}

await mkdir(join(THEME, 'assets', 'css'), { recursive: true })
await writeFile(join(THEME, 'assets', 'css', 'quireink-base.css'),
  '/* Copied from Quire Ink src/web/*.css.ts by tools/extract.ts, less the IDE chrome,\n'
  + '   which is lifted whole into quireink-ide.css. */\n'
  + PUBLIC_CSS.replace(IDE_SLICE, '\n') + '\n')
await writeFile(join(THEME, 'assets', 'css', 'quireink-ide.css'),
  '/* Quire Ink src/web/ide.css.ts, lifted whole by tools/extract.ts. Loaded only when\n'
  + '   the Customizer switch is on. */\n' + IDE_CSS + '\n')
await writeFile(join(THEME, 'assets', 'css', 'quireink-tokens.css'), tokens + '\n')

// ---------------------------------------------------------------- the mirror
//
// `rtl.css` in the theme ROOT is a WordPress convention with no PHP behind it: core hooks
// `locale_stylesheet()` onto `wp_head`, and for a locale whose text direction is rtl it links
// whatever `rtl.css` it finds. `wp_print_styles` runs at priority 8 and that at 10, so it
// lands after every sheet the theme enqueued, which is what makes a diff enough.
//
// It mirrors bridge.css too, which is the one sheet in here nobody generated. That is fine
// and it is the point: the mirror is derived from whatever the theme actually ships, so a
// hand-written rule that forgets RTL is answered without anyone remembering to answer it.
const bridge = await Bun.file(join(HERE, 'quire-ink', 'assets', 'css', 'bridge.css')).text()
const mirror = flipCss([
  PUBLIC_CSS.replace(IDE_SLICE, '\n'),
  IDE_CSS,
  tokens,
  bridge,
].join('\n'))
await writeFile(join(THEME, 'rtl.css'),
  '/* Generated by tools/rtl.ts from the four sheets this theme ships. Do not edit.\n'
  + '   Only what mirrors is here; everything else is already correct in both directions. */\n'
  + mirror.sheet)

// ---------------------------------------------------------------- the editor canvas
//
// The article's typography, again, aimed at `.editor-styles-wrapper` instead of at `.prose`.
// Built from the sheets this theme actually ships, including bridge.css, so a rule added there
// for a Gutenberg block reaches the editor without anybody remembering to copy it.
const editor = editorCss([PUBLIC_CSS.replace(IDE_SLICE, '\n'), IDE_CSS, bridge].join('\n'))
await writeFile(join(THEME, 'assets', 'css', 'editor.css'),
  '/* Generated by tools/editor-css.ts. Do not edit.\n'
  + '   Every rule scoped to .prose, re-addressed at the block editor canvas. */\n'
  + editor.sheet)

// ---------------------------------------------------------------- the pen, deliberately absent
//
// Quire Ink's pen sheet is NOT emitted here, and that is a decision rather than an omission
// (docs/decisions/0003-skip-what-gutenberg-cannot-express.md).
//
// The strokes are 273 KB of generated SVG keyed on `data-pen="0..N"` and `data-form=o`,
// attributes only Quire Ink's editor produces. The block editor has no way to write one, so
// on a WordPress site the sheet is 273 KB that can never match a single element. It was
// shipped for one afternoon, conditionally linked, before anyone asked who would author the
// markup it styles.
//
// Imported content still carries the attributes; `dev/seed/fetch.py` strips them on the way
// in for the same reason.

// ---------------------------------------------------------------- the faces

const FONT_SRC = join(QUIRE, 'src', 'assets', 'static', 'fonts')
const FONT_DST = join(THEME, 'assets', 'fonts')
await rm(FONT_DST, { recursive: true, force: true })
await mkdir(FONT_DST, { recursive: true })
const faces = (await readdir(FONT_SRC)).filter((f) => f.endsWith('.woff2'))
for (const f of faces) await copyFile(join(FONT_SRC, f), join(FONT_DST, f))

// ---------------------------------------------------------------- the islands

// Quire Ink's own reader bundles, built by its `build:assets`. `core` is the chrome (palette
// switch, rail, search overlay, back-to-top, newsletter) and `post` is the article (table of
// contents scrollspy, book mode, lightbox, quote copy, resume). They are copied rather than
// rewritten, which is the whole point — a second implementation of book mode would be a
// second thing to be wrong.
//
// Two of core's features talk to endpoints WordPress does not have (the newsletter form and
// the comment thread post to Quire Ink's API). They fail the way any fetch to a 404 fails,
// which is quietly; wiring them to WordPress is a decision for later and is written up in
// docs/gaps.md rather than patched in here.
const JS_SRC = join(QUIRE, 'src', 'assets', 'dist')
const JS_DST = join(THEME, 'assets', 'js')
await mkdir(JS_DST, { recursive: true })
const bundles = ['core.js', 'post.js']
for (const b of bundles) await copyFile(join(JS_SRC, b), join(JS_DST, b))

// ---------------------------------------------------------------- the owner's choices, as PHP
//
// Built in `tools/appearance-php.ts`, which runs the blog engine's emitters once per answer an
// owner could give. ~15 KB of PHP that never reaches a browser; what reaches the page is a few
// hundred bytes, and nothing at all when the owner has changed nothing.
if (!process.env.EXTRACT_OUT) {
  await writeFile(join(HERE, 'quire-ink', 'inc', 'generated-appearance.php'), APPEARANCE_PHP)
}

// ---------------------------------------------------------------- theme.json

// The block editor cannot read a CSS variable it was never told about, so the palette and
// the scale are declared a second time in its own dialect — pointing AT the variables rather
// than repeating their values, which is what keeps one source of truth after this file runs.
const palette = THEME_PRESETS[0]!.theme.light
const colorSlugs = Object.keys(palette)
const themeJson = {
  $schema: 'https://schemas.wp.org/trunk/theme.json',
  version: 3,
  settings: {
    appearanceTools: true,
    useRootPaddingAwareAlignments: true,
    // FROM THE ENGINE'S OWN NUMBERS, not from a pair of round rem values that happened to
    // look right. They were 38rem and 52rem — 608px and 832px — against a reading column of
    // 672px and a wide figure of 962px, so the editor drew every block 64px narrower than the
    // page would and "wide" meant two different widths on the two sides of Publish.
    layout: {
      contentSize: `${s.contentWidth}px`,
      wideSize: `${s.contentWidth + RAIL_W + RAIL_GAP}px`,
    },
    color: {
      defaultPalette: false,
      defaultGradients: false,
      custom: false,
      palette: colorSlugs.map((slug) => ({
        slug,
        name: slug.replace(/([A-Z])/g, ' $1').replace(/^./, (c) => c.toUpperCase()),
        color: `var(--c-${slug.replace(/([A-Z])/g, '-$1').toLowerCase()})`,
      })),
    },
    typography: {
      fluid: false,
      customFontSize: false,
      fontSizes: TYPE_ROLES.map((role) => ({
        slug: role,
        name: role.toUpperCase(),
        size: `var(--fs-${role})`,
      })),
    },
    spacing: {
      units: ['rem', 'px', '%'],
      spacingSizes: [
        { slug: 'tight', name: 'Tight', size: 'calc(var(--sp) * .5)' },
        { slug: 'normal', name: 'Normal', size: 'var(--sp)' },
        { slug: 'loose', name: 'Loose', size: 'calc(var(--sp) * 2)' },
      ],
    },
  },
  styles: {
    color: { background: 'var(--c-bg)', text: 'var(--c-text)' },
    typography: {
      fontFamily: 'var(--font-reading)',
      fontSize: 'var(--fs-body)',
      lineHeight: 'var(--lh-body)',
    },
    elements: {
      link: { color: { text: 'var(--c-link)' } },
      heading: {
        color: { text: 'var(--c-heading)' },
        typography: { fontWeight: 'var(--fw-heading)' },
      },
    },
  },
  templateParts: [
    { name: 'header', title: 'Header', area: 'header' },
    { name: 'footer', title: 'Footer', area: 'footer' },
  ],
}
if (!process.env.EXTRACT_OUT) await writeFile(join(HERE, 'quire-ink', 'theme.json'), JSON.stringify(themeJson, null, 2) + '\n')

// ---------------------------------------------------------------- the receipt

const sha = (await $`git -C ${QUIRE} rev-parse HEAD`.text()).trim()
const dirty = (await $`git -C ${QUIRE} status --porcelain`.text()).trim() !== ''
if (!process.env.EXTRACT_OUT) await writeFile(join(HERE, 'tools', 'extract-manifest.json'), JSON.stringify({
  takenFrom: { repo: 'quireink', commit: sha, workingTreeDirty: dirty },
  emitted: {
    'quire-ink/assets/css/quireink-base.css': PUBLIC_CSS.length - IDE_CSS.length - 1,
    'quire-ink/assets/css/quireink-ide.css': IDE_CSS.length,
    'quire-ink/assets/css/quireink-tokens.css': tokens.length,
    'quire-ink/rtl.css': mirror.sheet.length,
    'quire-ink/assets/fonts': faces.length,
    'quire-ink/assets/js': bundles,
  },
  palettes: THEME_PRESETS.map((p) => p.id),
  typeRoles: TYPE_ROLES,
  fontPreset: s.fontPreset,
  chromeFont: s.chromeFont,
}, null, 2) + '\n')

console.log(`base   ${PUBLIC_CSS.length - IDE_CSS.length - 1} B (IDE chrome lifted out)`)
console.log(`ide    ${IDE_CSS.length} B`)
console.log(`tokens ${tokens.length} B`)
console.log(`rtl    ${mirror.sheet.length} B, ${(mirror.sheet.match(/\{/g) ?? []).length} rules`)
console.log(`editor ${editor.sheet.length} B, ${editor.rules} rules`)
for (const w of mirror.warnings) console.log(`  ! rtl: ${w}`)
console.log(`fonts  ${faces.length} files`)
console.log(`js     ${bundles.join(', ')}`)
const c = APPEARANCE_COUNTS
console.log(`php    ${c.palettes} palettes x ${c.schemes} schemes, ${c.fonts} fonts, `
  + `${c.chrome} chrome, ${c.frames} frames (${APPEARANCE_PHP.length} B)`)
console.log(`from   quireink@${sha.slice(0, 7)}${dirty ? ' (dirty)' : ''}`)
